/** Labels that end in a name the file chose: only the fixed start is translated. */
const PREFIXES: readonly (readonly [en: string, es: string, de: string])[] = [
  ["Custom property: ", "Propiedad personalizada: ", "Benutzerdefinierte Eigenschaft: "],
  ["Comment part: ", "Parte de comentarios: ", "Kommentarteil: "],
  ["File: ", "Archivo: ", "Datei: "],
  ["Application data: ", "Datos de aplicación: ", "Anwendungsdaten: "],
  ["Unknown tag ", "Etiqueta desconocida ", "Unbekanntes Tag "],
];

/** The English labels this table translates, for its tests. */
export const TRANSLATED_FIELD_LABELS: readonly string[] = Object.keys(LABELS);

/** A field's label in `locale`: the processor's English label, translated
 *  when the table knows it, else unchanged. */
export function fieldLabel(label: string, locale: Locale): string {
  if (locale === "en") return label;
  const i = locale === "es" ? 0 : 1;
  const exact = LABELS[label];
  if (exact) return exact[i];
  // XMP properties are "XMP <name>": translate the name, keep XMP as a tag.
  if (label.startsWith("XMP ")) {
    const name = LABELS[label.slice(4)];
    if (name) return `${name[i]} (XMP)`;
  }
  for (const p of PREFIXES) {
    if (label.startsWith(p[0])) return p[i + 1] + label.slice(p[0].length);
  }
  // PNG text: "Title (compressed)" is a compressed Title chunk.
  if (label.endsWith(" (compressed)")) {
    const base = label.slice(0, -" (compressed)".length);
    return `${fieldLabel(base, locale)} ${i === 0 ? "(comprimido)" : "(komprimiert)"}`;
  }
  return label;
}
